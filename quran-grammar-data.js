// Forty lessons. The previous course was eight, which was not a course — it was
// a gesture at one, and it read that way.
//
// The goal has not changed: get a reader to the point where they can look at a
// verse and work out what it says. What changed is the admission that doing
// that properly takes forty lessons, not eight, and that the eight were
// compressing whole territories into single pages.
//
// The shape here came out of a design conversation with GPT-5.2 about where
// learners of Quranic Arabic actually stall. Its three sharpest calls, all
// taken:
//
//   FINDING THE ROOT MOVES LATER, to lesson 6. It was lesson 1. Beginners told
//   to find the root before they can strip prefixes and suffixes do not find
//   roots — they guess, confidently, and the root list then hands them the
//   wrong meaning. Affixes and particles first, then root extraction is a
//   mechanical step rather than a hunch.
//
//   ATTACHED PRONOUNS BECOME THREE LESSONS, not one — on nouns, on
//   prepositions, on verbs. This is the single biggest stall point in reading
//   the Qur'an: it is the reason a learner who knows every word in a verse
//   still cannot read the verse. رَبِّهِ, لَهُم and نَصَرَهُم fail in three
//   different ways and deserve three different pages.
//
//   PARTICLES BECOME EIGHT LESSONS, not one. They are the Qur'an's control
//   panel — negation, condition, exception, emphasis, purpose. Miss one and
//   you can know every content word in the āyah and still take the opposite
//   meaning from it. One lesson called "particles" was the worst compression
//   in the old course.
//
// ── The four units ──────────────────────────────────────────────────────────
//  1-10  SURVIVAL PARSING. The glue, and the shape of a word. Stops the early
//        collapse where every āyah is an unbreakable string.
// 11-22  VERBS FOR READERS. Who did what to whom. Recognition before grammar:
//        "he did / they do / do not do" long before anyone says "jussive".
// 23-32  MEANING FROM PATTERNS. The verb forms and derived nouns. This is where
//        vocabulary stops being a list and starts being a system — one root
//        seen through ten templates.
// 33-40  READING IʿRĀB WITHOUT AN EXAM. Case endings as a disambiguation tool,
//        never as a subject in themselves, and the long-verse machinery:
//        conditions, exceptions, purpose. Ends with a method, not a topic.
//
// Every lesson has ONE job and a plainly stated "you can now…". Where a lesson
// looks thin next to its neighbours that is deliberate: a lesson that teaches
// one thing gets remembered, and this course is read on a phone.
//
// Not generated by the model, and not generated at runtime. The topics of
// Quranic Arabic are settled, so the syllabus is hand-written here and the
