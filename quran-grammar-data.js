// Eight units. That is the whole course, and the shortness is deliberate.
//
// The goal is not to produce an Arabic grammarian. It is to get a reader to the
// point where they can look at a verse and work out what it says: find the root
// of each word, see what is stuck to it, and see how the words relate. Anything
// that does not serve that is not here.
//
// The course runs alongside the 300-root vocabulary track (quran-roots-data.js,
// served through the Vocabulary Builder). Roots give you the meanings; these
// eight units give you everything that happens TO those meanings inside a verse.
//
// ── The order, and why ──────────────────────────────────────────────────────
// 1-3  DECODE A WORD.  Unit 1 is the master key: strip a word back to its three
//      letters. Every other unit teaches through Arabic examples, so until a
//      learner can do this they are being shown evidence they cannot read — and
//      the root list only pays off once an unfamiliar word can be traced home.
//      Units 2 and 3 finish the job: an attached pronoun is the commonest reason
//      a known word looks unknown (رَبِّهِ), and particles are what let you chop
//      a verse into pieces.
// 4-5  WHAT THE WORD IS DOING.  Verbs carry the action. The present-tense prefix
//      letters (أ ن ي ت) send the learner straight back to unit 1, which is why
//      these sit here and not earlier.
// 6-8  HOW WORDS CONNECT.  Case endings must precede إضافة and the noun-adjective
//      phrase, because both are DEFINED by their endings — the kasrah on the
//      second noun IS the إضافة.
//
// Unit 6 is recognition only: reading what an ending tells you, never producing
// one. It is the most abstract of the eight and that constraint is what keeps it
// teachable.
//
// Not generated by the model. The topics of Quranic Arabic are settled, so
// hand-writing them gives a better and more consistent course than asking for
// one each time. The AI still writes each unit's explanation, examples and
// drills against the `structure` named here.
// ============================================================================

